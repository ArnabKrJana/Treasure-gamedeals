package com.example.treasure.data.repositoryImpl

/**
 * User preference enumeration for application visual themes.
 */
enum class AppTheme {
    /**
     * Follows the system-wide Android dark/light mode configuration.
     */
    SYSTEM,

    /**
     * Forces bright, light-mode Material 3 surfaces.
     */
    LIGHT,

    /**
     * Forces high-contrast, dark-mode Material 3 surfaces.
     */
    DARK
}
